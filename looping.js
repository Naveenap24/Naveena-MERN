// For Loop
console.log("Two Table");
console.log("For Loop");

for (let i = 1; i <= 10; i++) {
    console.log(i + " * 2 = " + (i * 2));
}

// While Loop
console.log("While Loop");

let i = 1;

while (i <= 10) {
    console.log("2 * " + i + " = " + (2 * i));
    i++;
}

// Do While Loop
console.log("Do While Loop");

let j = 1;

do {
    console.log("2 * " + j + " = " + (2 * j));
    j++;
} while (j <= 10);

